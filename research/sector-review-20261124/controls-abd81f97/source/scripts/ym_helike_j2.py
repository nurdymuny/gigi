"""Spin-2 colour-singlet sector of the sphere matrix model, solved in its own covariant basis.

Colour acts by q -> U q, so colour invariants are generated by G = q^T q (spatial, symmetric) and d = det q.
Space acts by G -> V G V^T. A spin-2 colour-singlet state is a traceless symmetric spatial tensor field
psi_ij(q). The traceless symmetric covariants of one symmetric matrix are a free module over the invariants,
generated by

    A1 = dev(G)   (degree 2),     A2 = dev(G^2)   (degree 4),     dev(X) = X - tr(X) I / 3,

because G^3 reduces to I, G and G^2 (Cayley-Hamilton). So the spin-2 part of the cutoff-N basis is

    { m(T, P, d) A_k e^{-x.x/2} : deg m + 2k <= N },  x = sqrt(alpha) q.

`scripts/test_ym_helike_j2.py` checks that count against the number of spin-2 multiplets in the 9-variable basis.

Exact tables, with N_x the gradient of generator x and D_N the derivative along it (G = q^T q):
    D_{grad T} G = 4G,   D_{grad P} G = 8G^2,   D_{grad d} G = 2d I,   Lap G = 6 I,   Lap G^2 = 22 G + 2T I.
Hence
    grad T . grad A1 = 4 A1,  grad T . grad A2 = 8 A2,
    grad P . grad A1 = 8 A2,  grad P . grad A2 = 16 (T A2 - e2 A1),  e2 = (T^2 - P)/2,
    grad d . grad A1 = 0,     grad d . grad A2 = 4 d A1,
    Lap A1 = 0,               Lap A2 = 22 A1.
(The trace of Lap G^2 gives Lap P = 28 T, as in the scalar module.) Frobenius contractions:
    A1:A1 = P - T^2/3,  A1:A2 = tr G^3 - TP/3,  A2:A2 = tr G^4 - P^2/3,
    tr G^3 = -T^3/2 + 3TP/2 + 3d^2,  tr G^4 = -T^4/2 + T^2 P + P^2/2 + 4T d^2.

Inner products use the Frobenius contraction summed over the five components. By Schur's lemma each member of a
multiplet then carries one fifth of every Gram entry. Normalising by the same contraction, the residual norm is
the per-member full-space residual, which equals the operator norm of the 5x5 residual Gram. Within one
multiplet the five members are exactly degenerate by construction.
"""
from __future__ import annotations

from fractions import Fraction as F

import mpmath as mp

import ym_helike_j0 as j0
from ym_helike_j0 import D, P, T, ZERO, _add, _mpf, degree, d_gen, laplacian, mono_mul, moment

# Derivative of A_k along grad x, as {(monomial, k'): coefficient}.
DIR = {
    (T, 1): {(ZERO, 1): F(4)},
    (T, 2): {(ZERO, 2): F(8)},
    (P, 1): {(ZERO, 2): F(8)},
    (P, 2): {((1, 0, 0), 2): F(16), ((2, 0, 0), 1): F(-8), ((0, 1, 0), 1): F(8)},
    (D, 1): {},
    (D, 2): {((0, 0, 1), 1): F(4)},
}
LAP_A = {1: {}, 2: {(ZERO, 1): F(22)}}
CONTRACT = {
    (1, 1): {(0, 1, 0): F(1), (2, 0, 0): F(-1, 3)},
    (1, 2): {(3, 0, 0): F(-1, 2), (1, 1, 0): F(7, 6), (0, 0, 2): F(3)},
    (2, 2): {(4, 0, 0): F(-1, 2), (2, 1, 0): F(1), (0, 2, 0): F(1, 6), (1, 0, 2): F(4)},
}
CONTRACT[(2, 1)] = CONTRACT[(1, 2)]
GEN_DEGREE = {1: 2, 2: 4}


def basis(N):
    out = [(m, k) for k in (1, 2) for m in j0.basis(N - GEN_DEGREE[k]) if N - GEN_DEGREE[k] >= 0]
    return sorted(out, key=lambda it: (degree(it[0]) + GEN_DEGREE[it[1]], it[1], it[0]))


def item_degree(it):
    return degree(it[0]) + GEN_DEGREE[it[1]]


def tensor_laplacian(m, k):
    """Lap(m A_k) = (Lap m) A_k + 2 sum_x (d_x m) (grad x . grad A_k) + m Lap A_k."""
    out = {}
    for mm, c in laplacian(m).items():
        _add(out, (mm, k), c)
    for x in (T, P, D):
        c, mx = d_gen(m, x)
        if c:
            for (mm, kk), cc in DIR[(x, k)].items():
                _add(out, (mono_mul(mx, mm), kk), 2 * c * cc)
    for (mm, kk), cc in LAP_A[k].items():
        _add(out, (mono_mul(m, mm), kk), cc)
    return out


def operator_parts(it):
    """Same split as the scalar module: alpha*A + B/(2 alpha) - 3 g alpha^{-3/2} C + g^2/(4 alpha^2) Dq."""
    m, k = it
    A = {key: -v / 2 for key, v in tensor_laplacian(m, k).items()}
    _add(A, it, F(item_degree(it)) + F(9, 2))
    _add(A, (mono_mul(m, (1, 0, 0)), k), F(-1, 2))
    B = {(mono_mul(m, (1, 0, 0)), k): F(1)}
    C = {(mono_mul(m, (0, 0, 1)), k): F(1)}
    Dq = {(mono_mul(m, (2, 0, 0)), k): F(1), (mono_mul(m, (0, 1, 0)), k): F(-1)}
    return A, B, C, Dq


def contracted_moment(m, k, l):
    """Exact <m A_k : A_l> under exp(-x.x), with <1> = 1."""
    return sum((c * moment(mono_mul(m, mm)) for mm, c in CONTRACT[(k, l)].items()), F(0))


def solve(N, g2, alpha, dps=60, nlev=None):
    j0.validate_inputs(N,g2,alpha,dps,nlev)
    if N<2:
        raise ValueError('tensor sector requires cutoff >=2')
    with mp.workdps(dps):
        coef = j0.coefficients(g2, alpha)
        items = basis(N)
        n = len(items)
        hs = []
        for it in items:
            h = {}
            for c, part in zip(coef, operator_parts(it)):
                for key, cc in part.items():
                    h[key] = h.get(key, 0) + c * _mpf(cc)
            hs.append(h)
        cache = {}

        def M(mono, k, l):
            key = (mono, min(k, l), max(k, l))
            v = cache.get(key)
            if v is None:
                v = cache[key] = _mpf(contracted_moment(mono, k, l))
            return v

        S, H, K = mp.matrix(n, n), mp.matrix(n, n), mp.matrix(n, n)
        for i in range(n):
            mi, ki = items[i]
            for j in range(i, n):
                mj, kj = items[j]
                S[i, j] = S[j, i] = M(mono_mul(mi, mj), ki, kj)
                hij = mp.fsum(c * M(mono_mul(mi, mm), ki, kk) for (mm, kk), c in hs[j].items())
                hji = mp.fsum(c * M(mono_mul(mj, mm), kj, kk) for (mm, kk), c in hs[i].items())
                if i != j and abs(hij - hji) > max(abs(hij), abs(hji), 1) * mp.mpf(10) ** (-(dps - 15)):
                    raise ArithmeticError(f"H not symmetric at {items[i]},{items[j]}: {abs(hij - hji)}")
                H[i, j] = H[j, i] = (hij + hji) / 2
                K[i, j] = K[j, i] = mp.fsum(c1 * c2 * M(mono_mul(m1, m2), k1, k2)
                                            for (m1, k1), c1 in hs[i].items() for (m2, k2), c2 in hs[j].items())
        out = j0.finish(S, H, K, dps, nlev)
    out.update({"cutoff": N, "g2": float(g2), "alpha": float(alpha), "basis": items, "spin": 2})
    return out


def branch(sol, index=0):
    """Branch dict in the shape quantum_ordering.ordering expects. The multiplet is exactly degenerate here."""
    E, R = sol["energies"], sol["residuals"]
    return {"low": E[index], "high": E[index], "residual": R[index],
            "next_low": E[index + 1], "next_residual": R[index + 1], "spin_error": 0.0}
