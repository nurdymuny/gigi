#[test]
fn berger_ricci_and_levi_civita_field() {
    for t in [0.5, 1.0, 2.0, 3.0, 7.5] {
        let geo = Geometry::new(LieAlgebra::su2_frame(), vec![t, 1.0, 1.0]);
        let ric = geo.ricci();
        let want = [2.0 * t, 0.0, 0.0, 0.0, 4.0 - 2.0 * t, 0.0, 0.0, 0.0, 4.0 - 2.0 * t];
        for k in 0..9 {
            assert!((ric[k] - want[k]).abs() < 1e-12, "Ric at t={t}: {ric:?}");
        }
        // The Levi-Civita connection, read as an so(3) = su(2) field, is the Berger member x = (2-t)/sqrt t, y = sqrt t.
        let gam = geo.levi_civita();
        let as_vec = |g: &Vec<f64>| [g[2 * 3 + 1], g[2], g[3]]; // so(3) matrix -> vector (M[2,1], M[0,2], M[1,0])
        let m = Member::berger(t).field().m;
        for i in 0..3 {
            let v = as_vec(&gam[i]);
            for a in 0..3 {
                assert!((v[a] - m[i][a]).abs() < 1e-12, "Levi-Civita field at t={t}, i={i}");
            }
        }
    }
}

#[test]
fn berger_field_energy_and_curvature() {
    // Fibre field on the Berger path is 3t - 4 (By Enough eq. (B)).
    for t in [1.5, 3.0, 6.0] {
        let m = Member::berger(t);
        assert!((m.fibre_field() - (3.0 * t - 4.0)).abs() < 1e-12);
        let f = m.field().curvature(&m.geometry());
        assert!((f[3 + 2][0] - m.fibre_field()).abs() < 1e-12, "F_12 = B tau_0");
    }
}

#[test]
fn su3_circle_split_along_the_stretched_direction() {
    // Family 2b: t on lambda_8, A = theta/2. The circle generated by X_8 (frame and gauge) is a symmetry.
    let alg = LieAlgebra::su_n(3);
    let t = 2.5;
    let mut g = vec![1.0; 8];
    g[7] = t;
    let geo = Geometry::new(alg.clone(), g.clone());
    let m: Vec<Vec<f64>> = (0..8).map(|a| (0..8).map(|b| if a == b { 0.5 / g[a].sqrt() } else { 0.0 }).collect()).collect();
    let field = Field::new(alg.clone(), m);
    let mut x8 = vec![0.0; 8];
    x8[7] = 1.0;
    for (p, q) in [(1, 0), (1, 1)] {
        let rep = Rep::su_n_pq(3, p, q);
        let sec = Sector::new(&geo, &field, &rep);
        let hg = sec.hessian_and_gauge();
        let split = ChargeSplit::new(&sec, &hg, &CircleGenerator { frame_gen: x8.clone(), gauge_gen: x8.clone() });
        println!("su3({p},{q}): {} charges, residuals {:.1e} {:.1e}, signs {:?}", split.field_bases.len(),
                 split.commutator_residual, split.intertwiner_residual, split.signs);
        assert!(split.commutator_residual < 1e-10 && split.intertwiner_residual < 1e-10);
        let blockwise = flatten(&split.slice_block_spectra(&hg));
        let dense = hg.slice_spectrum();
        assert_eq!(blockwise.len(), dense.len());
        let d = blockwise.iter().zip(&dense).map(|(a, b)| (a - b).abs()).fold(0.0, f64::max);
        assert!(d < 1e-10, "blockwise slice vs dense: {d:e}");
    }
}

#[test]
fn a_wrong_circle_is_reported_not_hidden() {
    // X_1 is not a symmetry of family 2b (it does not commute with X_8's stretch): the residual must be large.
    let alg = LieAlgebra::su_n(3);
    let mut g = vec![1.0; 8];
    g[7] = 2.5;
    let geo = Geometry::new(alg.clone(), g.clone());
    let m: Vec<Vec<f64>> = (0..8).map(|a| (0..8).map(|b| if a == b { 0.5 / g[a].sqrt() } else { 0.0 }).collect()).collect();
    let field = Field::new(alg, m);
    let rep = Rep::su_n_pq(3, 1, 0);
    let sec = Sector::new(&geo, &field, &rep);
    let hg = sec.hessian_and_gauge();
    let mut x4 = vec![0.0; 8];
    x4[3] = 1.0;
    let split = ChargeSplit::new(&sec, &hg, &CircleGenerator { frame_gen: x4.clone(), gauge_gen: x4 });
    assert!(split.commutator_residual > 1e-3, "a non-symmetry passed: {:e}", split.commutator_residual);
}

#[test]
fn problem_file_round_trip() {
    let p = Problem {
        frame: AlgebraSpec::Su2Frame,
        metric: vec![3.0, 1.0, 1.0],
        gauge: AlgebraSpec::So3Cross,
        field: FieldSpec::Su2Family { x: -0.5, y: 1.5 },
        rep: RepSpec::Spin { j: 3 },
        circle: Some(CircleSpec { frame_gen: vec![0.5, 0.0, 0.0], gauge_gen: vec![1.0, 0.0, 0.0] }),
    };
    let s = serde_json::to_string(&p).unwrap();
    let back: Problem = serde_json::from_str(&s).unwrap();
    assert_eq!(p, back);
    let r = back.solve();
    assert_eq!(r.sector_dim, 36);
    let lam = Member::new(-0.5, 1.5, 3.0).twist(3);
    let blocks = r.blocks.unwrap();
    let top = blocks.iter().max_by(|a, b| a.charge.partial_cmp(&b.charge).unwrap()).unwrap();
    assert_eq!(top.size, 1);
    assert!((top.lowest_h_plus_ggstar - lam).abs() < 1e-10);
    assert!(r.checks.rep_homomorphism < 1e-12 && r.checks.frame_jacobi < 1e-12);
}

#[test]
fn su4_sector_builds_and_is_hermitian_with_a_kernel() {
    // A = theta/2 on round SU(4), sector (1,0): the gauge map has the expected rank structure and H is Hermitian.
    let p = Problem {
        frame: AlgebraSpec::SuN { n: 4 },
        metric: vec![1.0; 15],
        gauge: AlgebraSpec::SuN { n: 4 },
        field: FieldSpec::MaurerCartan { s: 0.5 },
        rep: RepSpec::SuN { n: 4, p: 1, q: 0 },
        circle: None,
    };
    let r = p.solve();
    assert_eq!(r.sector_dim, 15 * 15 * 4);
    assert_eq!(r.spectrum_slice.len(), r.sector_dim - r.slice_rank_of_g);
    assert!(r.checks.gauge_invariance < 1e-12);
}
