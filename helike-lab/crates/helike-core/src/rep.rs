//! Representations of a frame algebra: anti-Hermitian matrices rho(X_a) with [rho X_a, rho X_b] = sum C_ab^c rho X_c.
//!
//! In a Peter-Weyl sector the left-invariant frame field X_a acts on the multiplicity space V by rho(X_a).

use crate::lie::LieAlgebra;
use crate::linalg::{self, CMat, C64};
use faer::Mat;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug)]
pub struct Rep {
    pub label: String,
    pub mats: Vec<CMat>,
}

/// A serialisable description of a representation, for problem files and receipts.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum RepSpec {
    /// SU(2) spin j/2 (dimension j+1) in the frame convention rho(e_a) = -2i J_a.
    Spin { j: usize },
    /// SU(N) irrep generated by e_1^{(x)p} (x) e_N^{*(x)q} inside V^{(x)p} (x) V^{*(x)q}: Dynkin (p, 0, ..., 0, q).
    SuN { n: usize, p: usize, q: usize },
    /// The trivial representation of dimension 1.
    Trivial,
}

impl Rep {
    pub fn dim(&self) -> usize {
        self.mats.first().map(|m| m.nrows()).unwrap_or(1)
    }

    pub fn from_spec(spec: &RepSpec, algebra_dim: usize) -> Self {
        match *spec {
            RepSpec::Spin { j } => Self::spin(j),
            RepSpec::SuN { n, p, q } => Self::su_n_pq(n, p, q),
            RepSpec::Trivial => Self::trivial(algebra_dim),
        }
    }

    pub fn trivial(algebra_dim: usize) -> Self {
        Self { label: "trivial".into(), mats: vec![linalg::zeros(1, 1); algebra_dim] }
    }

    /// rho(e_a) = -2i J_a on V_j (dim j+1), so that [rho_0, rho_1] = 2 rho_2 cyclically. Basis |l, m>, m = l..-l.
    pub fn spin(j: usize) -> Self {
        let s = j as f64 / 2.0;
        let d = j + 1;
        let m: Vec<f64> = (0..d).map(|k| s - k as f64).collect();
        let jz = Mat::from_fn(d, d, |a, b| if a == b { linalg::c(m[a]) } else { linalg::ZERO });
        let jp = Mat::from_fn(d, d, |a, b| {
            if b >= 1 && a == b - 1 {
                linalg::c((s * (s + 1.0) - m[b] * (m[b] + 1.0)).sqrt())
            } else {
                linalg::ZERO
            }
        });
        let jm = linalg::adjoint(&jp);
        let jx = linalg::scale(&(&jp + &jm), linalg::c(0.5));
        let jy = linalg::scale(&(&jp - &jm), C64::new(0.0, -0.5));
        let k = C64::new(0.0, -2.0);
        Self { label: format!("spin j={j}"), mats: vec![linalg::scale(&jx, k), linalg::scale(&jy, k), linalg::scale(&jz, k)] }
    }

    /// Direct sum of representations.
    pub fn direct_sum(&self, other: &Rep) -> Rep {
        let (a, b) = (self.dim(), other.dim());
        let mats = self
            .mats
            .iter()
            .zip(&other.mats)
            .map(|(x, y)| {
                Mat::from_fn(a + b, a + b, |i, j| {
                    if i < a && j < a {
                        x[(i, j)]
                    } else if i >= a && j >= a {
                        y[(i - a, j - a)]
                    } else {
                        linalg::ZERO
                    }
                })
            })
            .collect();
        Rep { label: format!("{} + {}", self.label, other.label), mats }
    }

    /// Tensor product: rho(X) (x) 1 + 1 (x) sigma(X).
    pub fn tensor(&self, other: &Rep) -> Rep {
        let (ia, ib) = (linalg::eye(self.dim()), linalg::eye(other.dim()));
        let mats = self.mats.iter().zip(&other.mats).map(|(x, y)| linalg::kron(x, &ib) + linalg::kron(&ia, y)).collect();
        Rep { label: format!("{} x {}", self.label, other.label), mats }
    }

    /// Dual: -rho(X)^T.
    pub fn dual(&self) -> Rep {
        let mats = self.mats.iter().map(|x| linalg::scale(&linalg::transpose(x), linalg::c(-1.0))).collect();
        Rep { label: format!("({})*", self.label), mats }
    }

    /// The subrepresentation generated from `v` by repeated application of the `lowering` operators (Gram-Schmidt
    /// with tolerance 1e-9), as an orthonormal basis B; returns rho restricted, B^H rho B.
    pub fn generated_submodule(&self, v: &[C64], lowering: &[CMat]) -> Rep {
        let dim = self.dim();
        let norm = |u: &[C64]| u.iter().map(|z| z.norm_sqr()).sum::<f64>().sqrt();
        let nv = norm(v);
        let mut basis: Vec<Vec<C64>> = vec![v.iter().map(|z| z / nv).collect()];
        let mut frontier = vec![0usize];
        while !frontier.is_empty() {
            let mut next = vec![];
            for &w in &frontier {
                for lo in lowering {
                    let mut u: Vec<C64> = (0..dim).map(|i| (0..dim).map(|k| lo[(i, k)] * basis[w][k]).sum()).collect();
                    for b in &basis {
                        let p: C64 = b.iter().zip(&u).map(|(bi, ui)| bi.conj() * ui).sum();
                        for i in 0..dim {
                            u[i] -= p * b[i];
                        }
                    }
                    let nu = norm(&u);
                    if nu > 1e-9 {
                        basis.push(u.iter().map(|z| z / nu).collect());
                        next.push(basis.len() - 1);
                    }
                }
            }
            frontier = next;
        }
        let b = Mat::from_fn(dim, basis.len(), |i, k| basis[k][i]);
        let bh = linalg::adjoint(&b);
        Rep { label: self.label.clone(), mats: self.mats.iter().map(|x| &bh * x * &b).collect() }
    }

    /// SU(N) irrep (p, 0, ..., 0, q), in the basis X_a = -(i/2) lambda_a of `LieAlgebra::su_n(n)`. Built as in
    /// `su3_irrep` of `ricci_su3_test2_family.py`: the submodule of V^{(x)p} (x) V^{*(x)q} generated from
    /// e_1^{(x)p} (x) e_N^{(x)q} by the lowering operators E_{k+1,k} (simple roots).
    pub fn su_n_pq(n: usize, p: usize, q: usize) -> Rep {
        let x = LieAlgebra::su_n_matrices(n);
        if p + q == 0 {
            return Rep { label: format!("su{n}({p},{q})"), mats: vec![linalg::zeros(1, 1); x.len()] };
        }
        let fund = Rep { label: "V".into(), mats: x.clone() };
        let dual = fund.dual();
        let mut big = if p > 0 { fund.clone() } else { dual.clone() };
        for k in 1..(p + q) {
            big = big.tensor(if k < p { &fund } else { &dual });
        }
        // highest-weight vector e_1^p (x) e_N^q as a Kronecker product.
        let mut v = vec![linalg::ONE];
        for k in 0..(p + q) {
            let e: Vec<C64> = (0..n).map(|i| if i == if k < p { 0 } else { n - 1 } { linalg::ONE } else { linalg::ZERO }).collect();
            v = v.iter().flat_map(|a| e.iter().map(move |b| a * b)).collect();
        }
        // lowering E_{k+1,k} acting on the big space: sum over tensor slots of E (fund) or -E^T (dual).
        let unit = |r: usize, s: usize| -> CMat { Mat::from_fn(n, n, |i, j| if i == r && j == s { linalg::ONE } else { linalg::ZERO }) };
        let lowering: Vec<CMat> = (0..n - 1)
            .map(|k| {
                let e = unit(k + 1, k);
                let slot_ops: Vec<CMat> = (0..p + q).map(|s| if s < p { e.clone() } else { linalg::scale(&linalg::transpose(&e), linalg::c(-1.0)) }).collect();
                let mut total = linalg::zeros(n.pow((p + q) as u32), n.pow((p + q) as u32));
                for s in 0..p + q {
                    let mut t = if s == 0 { slot_ops[0].clone() } else { linalg::eye(n) };
                    for u in 1..p + q {
                        t = linalg::kron(&t, &if u == s { slot_ops[s].clone() } else { linalg::eye(n) });
                    }
                    total = total + t;
                }
                total
            })
            .collect();
        let mut r = big.generated_submodule(&v, &lowering);
        r.label = format!("su{n}({p},{q})");
        r
    }

    /// Largest violation of [rho X_a, rho X_b] = sum_c C_ab^c rho X_c, and of anti-Hermiticity.
    pub fn homomorphism_error(&self, alg: &LieAlgebra) -> f64 {
        let n = alg.dim;
        assert_eq!(self.mats.len(), n, "representation has the wrong number of generators");
        let mut e = 0.0f64;
        for a in 0..n {
            let ah = &self.mats[a] + linalg::adjoint(&self.mats[a]);
            e = e.max(linalg::max_abs(&ah));
            for b in 0..n {
                let mut rhs = linalg::zeros(self.dim(), self.dim());
                for k in 0..n {
                    let cab = alg.get(a, b, k);
                    if cab != 0.0 {
                        rhs = rhs + linalg::scale(&self.mats[k], linalg::c(cab));
                    }
                }
                e = e.max(linalg::max_abs_diff(&linalg::commutator(&self.mats[a], &self.mats[b]), &rhs));
            }
        }
        e
    }
}

/// Dimension of the SU(N) irrep (p, 0, ..., 0, q) by the Weyl dimension formula.
pub fn su_n_pq_dim(n: usize, p: usize, q: usize) -> usize {
    // Partition of (p, 0, ..., 0, q): (p+q, q, ..., q, 0); dim = prod_{i<j} (part_i - part_j + j - i)/(j - i).
    let mut part = vec![q as i64; n];
    part[0] = (p + q) as i64;
    part[n - 1] = 0;
    let mut num = 1i128;
    let mut den = 1i128;
    for i in 0..n {
        for j in i + 1..n {
            num *= (part[i] - part[j] + (j - i) as i64) as i128;
            den *= (j - i) as i128;
        }
    }
    (num / den) as usize
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spin_is_a_frame_representation() {
        let f = LieAlgebra::su2_frame();
        for j in 0..7 {
            let r = Rep::spin(j);
            assert_eq!(r.dim(), j + 1);
            assert!(r.homomorphism_error(&f) < 1e-12, "spin {j}");
        }
    }

    #[test]
    fn su_n_irreps_have_weyl_dimensions() {
        for (n, p, q) in [(3, 1, 0), (3, 0, 1), (3, 1, 1), (3, 2, 0), (3, 2, 1), (3, 3, 0), (4, 1, 0), (4, 1, 1), (4, 2, 0)] {
            let alg = LieAlgebra::su_n(n);
            let r = Rep::su_n_pq(n, p, q);
            assert_eq!(r.dim(), su_n_pq_dim(n, p, q), "dim su{n}({p},{q})");
            assert!(r.homomorphism_error(&alg) < 1e-11, "hom su{n}({p},{q})");
        }
    }
}
